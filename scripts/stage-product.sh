#!/usr/bin/env bash
# Install the product layer and its pinned native bundle into the Android tree.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
TREE=$ROOT/src
NB=$ROOT/nvidia/release/native
PIN=$ROOT/nvidia/product/vendor/nvidia-prolapse/native-bundle.json
if [ -f "$PIN" ]; then
    NB=$ROOT/$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1]))["path"])' "$PIN")
fi
ANGLE=$ROOT/nvidia/release/guest-prebuilts
WN=$ROOT/nvidia/waydroid-nvidia/nvidia-prolapse
MEDIA=$WN/media/odm/etc

python3 -I - "$NB" "$PIN" <<'PY'
import hashlib, json, os, sys
nb = sys.argv[1]
pin = sys.argv[2]
if os.path.isfile(pin):
    expected = json.load(open(pin))["build_record_sha256"]
    actual = hashlib.sha256(open(os.path.join(nb, "BUILD-RECORD.json"), "rb").read()).hexdigest()
    if actual != expected:
        sys.exit(f"native build-record mismatch: {actual} != {expected}")
rec = json.load(open(os.path.join(nb, "BUILD-RECORD.json")))
bad = [p for p, h in rec["files"].items() if p.startswith("payload/")
       and hashlib.sha256(open(os.path.join(nb, p), "rb").read()).hexdigest() != h]
if bad:
    sys.exit(f"native bundle mismatch: {bad}")
print("native bundle", rec["release"], "sha256 ok")
PY

for d in device/nvidia-prolapse vendor/nvidia-prolapse; do
    mkdir -p "$TREE/$d"
    rsync -rlp --checksum --delete --exclude=/identity.mk --exclude=/prebuilts --exclude=/media-src \
        "$ROOT/nvidia/product/$d/" "$TREE/$d/"
done

rec_sha=$(sha256sum "$NB/BUILD-RECORD.json" | cut -d' ' -f1)
version=$(python3 -I -c 'import json,sys; print(json.load(open(sys.argv[1]))["release"])' "$NB/BUILD-RECORD.json")
printf '%s\n' '# Generated by scripts/stage-product.sh from the native bundle.' \
    'PRODUCT_VENDOR_PROPERTIES += \' \
    "    ro.vendor.nvidia_prolapse.version=$version \\" \
    "    ro.vendor.nvidia_prolapse.build_record=$rec_sha" > "$TREE/vendor/nvidia-prolapse/identity.mk"

pre=$TREE/vendor/nvidia-prolapse/prebuilts
mkdir -p "$pre/native" "$pre/angle/vendor" "$pre/media/odm/etc"
rsync -rlp --checksum --delete "$NB/payload/" "$pre/native/payload/"
rsync -rlp --checksum "$NB/BUILD-RECORD.json" "$pre/native/"
rsync -rlp --checksum --delete "$MEDIA/" "$pre/media/odm/etc/"
rsync -rlp --checksum --delete --include='*/' --include='lib*_angle.so' --exclude='*' "$ANGLE/vendor/" "$pre/angle/vendor/"
# Codec2 service sources for Android.bp (built in this tree, see there)
src=$TREE/vendor/nvidia-prolapse/media-src
mkdir -p "$src/core" "$src/c2" "$src/video"
rsync -rlp --checksum --delete "$WN/media/core/" "$src/core/"
rsync -rlp --checksum --delete "$WN/media/c2/" "$src/c2/"
rsync -rlp --checksum --delete "$WN/driver-source/native/video/nv_video.h" "$WN/driver-source/native/video/nv_venc.h" "$src/video/"
echo "product layer staged: $version build_record=$rec_sha"
